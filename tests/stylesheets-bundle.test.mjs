import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";

const repoRoot = process.cwd();
const htmlPages = [
  "index.html",
  "about.html",
  "admin.html",
  "editor.html",
  "get-involved.html",
  "guide.html",
  "investigation.html",
  "investigations.html",
  "map.html",
  "merch.html",
  "submit.html"
];

test("pages load the bundled stylesheet instead of split partial links", async () => {
  for (const relativePath of htmlPages) {
    const content = await fs.readFile(path.join(repoRoot, relativePath), "utf8");
    assert.match(content, /<link rel="stylesheet" href="\.\/styles\.css">/);
    assert.doesNotMatch(content, /\.\/styles\/00-fonts\.css/);
  }
});

test("generated stylesheet is bundled instead of chaining @import directives", async () => {
  const content = await fs.readFile(path.join(repoRoot, "styles.css"), "utf8");
  assert.match(content, /Generated by tooling\/build-styles\.mjs/);
  assert.doesNotMatch(content, /@import url\("/);
});

test("generated stylesheet rewrites self-hosted font paths relative to bundled output", async () => {
  const content = await fs.readFile(path.join(repoRoot, "styles.css"), "utf8");
  assert.match(content, /url\("\.\/styles\/fonts\/ibm-plex-sans-latin\.woff2"\)/);
  assert.match(content, /url\("\.\/styles\/fonts\/spectral-700-latin\.woff2"\)/);
  assert.doesNotMatch(content, /url\("\.\/fonts\//);
});
